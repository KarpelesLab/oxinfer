//! Emits `has_simd` when a hand-written SIMD kernel module exists for the target: NEON on
//! aarch64, AVX2/scalar-dispatch on x86-64, and simd128 on wasm32 when that target feature is
//! enabled (`-C target-feature=+simd128`). Everything else uses the scalar paths in `kernels.rs`.
fn main() {
    println!("cargo:rustc-check-cfg=cfg(has_simd)");
    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let features = std::env::var("CARGO_CFG_TARGET_FEATURE").unwrap_or_default();
    let simd = match arch.as_str() {
        "aarch64" | "x86_64" => true,
        "wasm32" => features.split(',').any(|f| f == "simd128"),
        _ => false,
    };
    if simd {
        println!("cargo:rustc-cfg=has_simd");
    }
    println!("cargo:rerun-if-changed=build.rs");
    webui_assets();
}

/// `$OUT_DIR/webui_assets.rs`: `ASSETS`, every file of the built web GUI (`src/server/webui`,
/// written by `npm run build:native` in `web/` and committed, so that building needs no node)
/// as `(path, include_bytes!(...))`, for `oxinfer web` (`src/server/web.rs`). Empty when the
/// folder is missing.
fn webui_assets() {
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("webui_assets.rs");
    let root = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("src/server/webui");
    println!("cargo:rerun-if-changed=src/server/webui");
    let mut files = Vec::new();
    let mut stack = vec![root.clone()];
    while let Some(dir) = stack.pop() {
        let Ok(rd) = std::fs::read_dir(&dir) else { continue };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                println!("cargo:rerun-if-changed={}", p.display());
                stack.push(p);
            } else if let Ok(rel) = p.strip_prefix(&root) {
                let rel = rel.to_string_lossy().replace('\\', "/");
                if !rel.starts_with('.') && !rel.contains("/.") {
                    files.push((rel, p));
                }
            }
        }
    }
    files.sort();
    let mut src = String::from(
        "/// The built web GUI: (path, bytes) of each file (generated by build.rs).\npub static ASSETS: &[(&str, &[u8])] = &[\n",
    );
    for (rel, p) in &files {
        src.push_str(&format!("    ({rel:?}, include_bytes!({:?})),\n", p.display().to_string()));
    }
    src.push_str("];\n");
    std::fs::write(out, src).unwrap();
}
